export interface IgnoreOperation {
  vuln_id: string;
  title: string;
  severity: string;
  risk_score: number | null;
  fixable: boolean;
  project_id: string;
  project_name: string;
  display_path: string;
  action: 'ignore' | 'unignore';
}

export interface IgnoreAnalysis {
  to_ignore: IgnoreOperation[];
  to_update: IgnoreOperation[];
  to_unignore: IgnoreOperation[];
}

export interface ApplyProgress {
  action: string;
  vuln_id: string;
  project_id: string;
  status: 'ok' | 'error';
  error?: string | null;
  done: number;
  total: number;
}

// ---------------------------------------------------------------------------
// analyzeIgnores — categorise operations needed
// ---------------------------------------------------------------------------

export function analyzeIgnores(
  results: ScanResult[],
  minRiskScore: number,
  snykFilePath: string,
): IgnoreAnalysis {
  const policy = loadSnykPolicy(snykFilePath);
  const existingIgnores = (policy['ignore'] as Record<string, unknown>) ?? {};

  const toIgnore: IgnoreOperation[] = [];
  const toUpdate: IgnoreOperation[] = [];
  const toUnignore: IgnoreOperation[] = [];

  for (const proj of results) {
    const projectId = proj.id;
    const projectName = proj.name ?? 'Unknown';
    const displayPath = getProjectDisplayPath(projectName);

    for (const rawIssue of proj.issues ?? []) {
      const issue = rawIssue as Record<string, unknown>;
      const issueData = (issue['issueData'] as Record<string, unknown>) ?? {};
      const vulnId = (issueData['id'] as string) || (issue['id'] as string) || '';
      if (!vulnId) continue;

      const priority = (issue['priority'] as Record<string, unknown>) ?? {};
      const rawScore = priority['score'];
      const score = rawScore != null ? parseInt(String(rawScore), 10) : null;
      const fixable = !isNotFixable(issue);
      const severity = (issueData['severity'] as string) ?? 'medium';

      let qualifies: boolean;
      if (minRiskScore > 0) {
        const scoreQualifies = score != null && !isNaN(score) && score >= minRiskScore;
        qualifies = !fixable && scoreQualifies;
      } else {
        qualifies = !fixable;
      }

      const alreadyIgnored = vulnId in existingIgnores;

      const baseEntry = {
        vuln_id: vulnId,
        title: (issueData['title'] as string) ?? vulnId,
        severity,
        risk_score: isNaN(score as number) ? null : score,
        fixable,
        project_id: projectId,
        project_name: projectName,
        display_path: displayPath,
      };

      if (qualifies) {
        if (alreadyIgnored) toUpdate.push({ ...baseEntry, action: 'ignore' });
        else toIgnore.push({ ...baseEntry, action: 'ignore' });
      } else if (alreadyIgnored && fixable) {
        toUnignore.push({ ...baseEntry, action: 'unignore' });
      }
    }
  }

  return { to_ignore: toIgnore, to_update: toUpdate, to_unignore: toUnignore };
}

// ---------------------------------------------------------------------------
// applyIgnores — apply via Snyk API with concurrency
// ---------------------------------------------------------------------------

async function applyWithRetry(
  fn: () => Promise<void>,
  maxRetries = 5,
): Promise<{ ok: boolean; error?: string }> {
  for (let attempt = 0; attempt < maxRetries; attempt++) {
    try {
      await fn();
      return { ok: true };
    } catch (err) {
      const msg = String(err).toLowerCase();
      const isRateLimit = msg.includes('429') || msg.includes('rate limit') || msg.includes('too many requests');
      if (isRateLimit && attempt < maxRetries - 1) {
        await new Promise((r) => setTimeout(r, 10_000 * Math.pow(2, attempt)));
        continue;
      }
      return { ok: false, error: String(err) };
    }
  }
  return { ok: false, error: 'Max retries exceeded' };
}

export async function applyIgnores(
  client: SnykClient,
  orgId: string,
  operations: Array<{ action?: 'ignore' | 'unignore'; vuln_id: string; project_id: string }>,
  reason: string,
  expires: string,
  onProgress: (p: ApplyProgress) => void,
  disregardIfFixable = true,
): Promise<{ succeeded: number; failed: number }> {
  if (operations.length === 0) return { succeeded: 0, failed: 0 };

  const total = operations.length;
  let done = 0;
  let succeeded = 0;
  let failed = 0;

  // Apply with max 5 concurrent workers
  const CONCURRENCY = 5;
  let idx = 0;

  async function worker() {
    while (idx < operations.length) {
      const i = idx++;
      const op = operations[i];

      // Default to 'ignore' unless explicitly 'unignore'. This guards against
      // callers accidentally omitting the `action` field — silently treating
      // an unrecognised/missing action as an unignore would mean nothing ever
      // gets ignored, which is far more dangerous than the reverse.
      const action: 'ignore' | 'unignore' = op.action === 'unignore' ? 'unignore' : 'ignore';

      const { ok, error } = await applyWithRetry(async () => {
        if (action === 'ignore') {
          await client.ignoreIssue(orgId, op.project_id, op.vuln_id, reason, expires, disregardIfFixable);
        } else {
          await client.unignoreIssue(orgId, op.project_id, op.vuln_id);
        }
      });

      done++;
      if (ok) succeeded++;
      else failed++;

      onProgress({
        action,
        vuln_id: op.vuln_id,
        project_id: op.project_id,
        status: ok ? 'ok' : 'error',
        error: error ?? null,
        done,
        total,
      });
    }
  }

  const workers = Array.from({ length: Math.min(CONCURRENCY, operations.length) }, () => worker());
  await Promise.all(workers);

  return { succeeded, failed };
}

// ---------------------------------------------------------------------------
// generateSnykFiles — write per-project .snyk files
// ---------------------------------------------------------------------------

export function generateSnykFiles(
  results: ScanResult[],
  filterMode: string,
  minRiskScore: number,
  snykIgnoresDir: string,
): { files_written: number; total_ignores: number; files: string[] } {
  const validModes = ['all', 'fixable', 'non_fixable', 'non_fixable_above_score'];
  if (!validModes.includes(filterMode)) {
    throw new Error(`filterMode must be one of: ${validModes.join(', ')}`);
  }

  const now = new Date().toISOString().replace(/\.\d+Z$/, '.000Z');
  let filesWritten = 0;
  let totalIgnores = 0;
  const writtenPaths: string[] = [];

  for (const proj of results) {
    const issues = proj.issues ?? [];
    if (issues.length === 0) continue;

    const projectName = proj.name ?? 'unknown';
    const folderName = getProjectFolder(projectName);
    const policy: { version: string; ignore: PolicyIgnore } = { version: 'v1.5.0', ignore: {} };
    const vulnMetadata: Record<string, VulnMeta> = {};
    let projIgnoreCount = 0;

    for (const rawIssue of issues) {
      const issue = rawIssue as Record<string, unknown>;
      const issueData = (issue['issueData'] as Record<string, unknown>) ?? {};
      const vulnId = (issueData['id'] as string) || (issue['id'] as string) || '';
      if (!vulnId) continue;

      const notFixable = isNotFixable(issue);
      const priority = (issue['priority'] as Record<string, unknown>) ?? {};
      const rawScore = priority['score'];
      const score = rawScore != null ? parseInt(String(rawScore), 10) : null;
      const severity = (issueData['severity'] as string) ?? 'medium';

      let passes = false;
      if (filterMode === 'all') {
        passes = true;
      } else if (filterMode === 'fixable') {
        passes = !notFixable;
      } else if (filterMode === 'non_fixable') {
        passes = notFixable;
      } else if (filterMode === 'non_fixable_above_score') {
        if (!notFixable || score == null || isNaN(score)) passes = false;
        else passes = score >= minRiskScore;
      }

      if (!passes) continue;

      const days = scoreToDays(score != null && !isNaN(score) ? score : null, severity);
      const reason =
        score != null && !isNaN(score)
          ? `Accepted due to risk score of ${score}`
          : 'Accepted - not fixable';
      const expiresDate = new Date(Date.now() + days * 86400 * 1000)
        .toISOString()
        .replace(/\.\d+Z$/, '.000Z');

      policy.ignore[vulnId] = [{ '*': { reason, expires: expiresDate, created: now } }];
      vulnMetadata[vulnId] = {
        id: vulnId,
        title: (issueData['title'] as string) ?? vulnId,
        severity,
        risk_score: score != null && !isNaN(score) ? score : null,
        cwe: ((issueData['identifiers'] as Record<string, unknown>)?.['CWE'] as string[]) ?? [],
        reachability: 'N/A',
        fixable: !notFixable,
      };
      projIgnoreCount++;
    }

    if (projIgnoreCount > 0) {
      const folder = path.join(snykIgnoresDir, folderName);
      fs.mkdirSync(folder, { recursive: true });
      const snykFilePath = path.join(folder, '.snyk');
      writeSnykFile(snykFilePath, policy, vulnMetadata);
      filesWritten++;
      totalIgnores += projIgnoreCount;
      writtenPaths.push(snykFilePath);
    }
  }

  return { files_written: filesWritten, total_ignores: totalIgnores, files: writtenPaths };
}
