export function isNotFixable(issue: Record<string, unknown>): boolean {
  if (issue['isUpgradable'] || issue['isPatchable'] || issue['isPinnable']) return false;
  const fi = issue['fixInfo'] as Record<string, unknown> | undefined;
  if (fi?.['isUpgradable'] || fi?.['isPatchable'] || fi?.['isPinnable'] || fi?.['isFixable']) return false;
  return true;
}

export function scoreToDays(score: number | null, severity: string): number {
  const severityFallback: Record<string, number> = {
    critical: 7,
    high: 14,
    medium: 30,
    low: 60,
  };
  if (score == null) return severityFallback[severity] ?? 30;
  const s = Math.round(score);
  if (s <= 200) return 90;
  if (s <= 400) return 60;
  if (s <= 600) return 30;
  if (s <= 800) return 14;
  return 7;
}

export function getProjectFolder(projectName: string): string {
  let name = projectName;

  // Strip org prefix (before first /)
  const beforeBranchOrColon = name.split('(')[0].split(':')[0];
  if (beforeBranchOrColon.includes('/')) {
    name = name.split('/').slice(1).join('/');
  }

  let repo = name;
  let subpath = '';

  if (name.includes('(')) {
    repo = name.split('(')[0];
    const afterParen = name.includes(')') ? name.split(')').slice(1).join(')') : '';
    if (afterParen.startsWith(':')) subpath = afterParen.slice(1);
  } else if (name.includes(':')) {
    const parts = name.split(':');
    repo = parts[0];
    subpath = parts.slice(1).join(':');
    if (subpath.startsWith('env-') && subpath.includes(':')) {
      subpath = subpath.split(':').slice(1).join(':');
      if (subpath.startsWith('/')) subpath = subpath.slice(1);
    }
  }

  if (subpath) {
    const parts = subpath.rsplit ? subpath.rsplit('/', 1) : subpath.split('/');
    const lastPart = parts[parts.length - 1];
    if (parts.length >= 2 && lastPart.includes('.')) {
      subpath = parts.slice(0, -1).join('/');
    } else if (lastPart.includes('.') && !subpath.includes('/')) {
      subpath = '';
    }
  }

  repo = repo.trim();
  subpath = subpath.trim().replace(/^\/|\/$/g, '');

  if (subpath) return `${repo}/${subpath}`;
  return repo || 'unknown_project';
}

