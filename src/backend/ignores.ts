// ---------------------------------------------------------------------------
// .snyk YAML file writer (no external dep)
// ---------------------------------------------------------------------------

interface IgnoreEntry {
  reason: string;
  expires: string;
  created: string;
}

interface PolicyIgnore {
  [vulnId: string]: Array<{ '*': IgnoreEntry }>;
}

interface VulnMeta {
  id: string;
  title: string;
  severity: string;
  risk_score: number | null;
  cwe: string[];
  reachability: string;
  fixable: boolean;
}

function writeSnykFile(
  filePath: string,
  policy: { version: string; ignore: PolicyIgnore },
  vulnMetadata: Record<string, VulnMeta>,
): void {
  const lines: string[] = [];
  lines.push('# Snyk policy file — auto-generated by Snyk Commander');
  lines.push(`version: ${policy.version}`);
  lines.push('ignore:');

  for (const [vulnId, entries] of Object.entries(policy.ignore)) {
    const meta = vulnMetadata[vulnId];
    if (meta) {
      const cweStr = meta.cwe.length > 0 ? meta.cwe.join(', ') : 'N/A';
      const riskDisplay = meta.risk_score != null ? String(meta.risk_score) : 'N/A';
      lines.push(`  # ${meta.title}`);
      lines.push(`  # ID: ${vulnId}`);
      lines.push(`  # CWE: ${cweStr}`);
      lines.push(`  # Severity: ${meta.severity}`);
      lines.push(`  # Risk Score: ${riskDisplay}`);
      lines.push(`  # Reachability: ${meta.reachability}`);
      lines.push(`  # Fixable: ${meta.fixable ? 'Yes' : 'No'}`);
    }
    lines.push(`  ${vulnId}:`);
    for (const entry of entries) {
      for (const [pathKey, details] of Object.entries(entry)) {
        lines.push(`    - '${pathKey}':`);
        lines.push(`        reason: ${details.reason}`);
        lines.push(`        expires: ${details.expires}`);
        lines.push(`        created: ${details.created}`);
      }
    }
  }

  fs.writeFileSync(filePath, lines.join('\n') + '\n', 'utf8');
}

// ---------------------------------------------------------------------------
// Load existing .snyk policy (basic YAML parser for the ignore section)
// ---------------------------------------------------------------------------

function loadSnykPolicy(snykFilePath: string): Record<string, unknown> {
  try {
    // Use js-yaml — bundled via esbuild
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const yaml = require('js-yaml') as { load: (s: string) => unknown };
    if (!fs.existsSync(snykFilePath)) return { version: 'v1.5.0', ignore: {} };
    const raw = fs.readFileSync(snykFilePath, 'utf8');
    const parsed = yaml.load(raw) as Record<string, unknown> | null;
    const data = parsed ?? {};
    if (!data['ignore']) data['ignore'] = {};
    return data;
  } catch {
    return { version: 'v1.5.0', ignore: {} };
  }
}

